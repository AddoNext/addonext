export function getWidgetIcon(widgetId: string, iconClass?: string): IconDefinition {
  const resolved = WIDGET_ICON_MAP[widgetId];
  if (resolved) return resolved;
  const name = (iconClass ?? "")
    .split(/\s+/)
    .find((c) => c.startsWith("eicon-"))
    ?.replace(/^eicon-/, "")
    ?? "";
  const byEicon: Record<string, IconDefinition> = {
    button: faSquare,
    accordion: faChevronDown,
    heading: faHeading,
    "bar-chart": faChartBar,
  };
  return byEicon[name] ?? faPuzzlePiece;
}
